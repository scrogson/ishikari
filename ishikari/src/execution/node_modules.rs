//! Node types found while the host runs, beyond those it registers in Rust: modules its
//! operators upload through the admin. `ishikari-wasm`'s `WasmModules` keeps WebAssembly
//! components as modules.

use std::collections::HashMap;
use std::sync::Arc;
use std::time::Duration;

use chrono::{DateTime, Utc};

use super::executor::NodeHandler;
use super::node_types::NodeSpec;

/// A node type found while the host runs: what [`NodeTypes`](super::NodeTypes) asks for a type
/// it has no handler for, and what the admin lists and uploads to
/// (`ishikari_admin::AppState::with_node_modules`).
#[async_trait::async_trait]
pub trait NodeModules: Send + Sync {
    /// The handler of the module `node_type` for a run created at `as_of`: its latest version
    /// uploaded by then, so a run and its retries run the same code. `None` when there's no
    /// such module.
    async fn handler(
        &self,
        node_type: &str,
        as_of: DateTime<Utc>,
    ) -> Result<Option<Arc<dyn NodeHandler>>, ModuleError>;

    /// The latest version of each module, by name.
    async fn modules(&self) -> Result<Vec<NodeModule>, ModuleError>;

    /// The node type `bytes` describe themselves as, without keeping them: what an upload of
    /// them would be, or [`ModuleError::Invalid`] when it would be refused.
    async fn describe(&self, bytes: &[u8]) -> Result<NodeSpec, ModuleError>;

    /// Keep `upload` as the next version of the module it names, or as nothing new when its
    /// bytes and grants are the latest version's.
    async fn upload(&self, upload: ModuleUpload) -> Result<NodeModule, ModuleError>;

    /// Run `upload` once as a node given `inputs`, within its grants, without keeping it: the
    /// admin's test run of a module before it's uploaded. [`ModuleError::Invalid`] when it
    /// would be refused; a run that fails is a [`TestRun`] whose output is why.
    async fn test_run(
        &self,
        upload: ModuleUpload,
        inputs: HashMap<String, serde_json::Value>,
    ) -> Result<TestRun, ModuleError>;
}

/// How a module's test run went.
#[derive(Debug, Clone, PartialEq)]
pub struct TestRun {
    /// The node type the module describes itself as.
    pub spec: NodeSpec,
    /// What its node returned, or why it failed.
    pub output: Result<serde_json::Value, String>,
    /// What it logged.
    pub logs: Vec<String>,
    /// The names of the secrets it read, of those granted.
    pub secrets: Vec<String>,
}

/// A version of a module: the node type it provides, and what it may do.
#[derive(Debug, Clone, PartialEq)]
pub struct NodeModule {
    /// The node type, as the module describes itself; its name is the module's.
    pub spec: NodeSpec,
    /// 1 for its first upload, then one more for each upload of different bytes or grants.
    pub version: i32,
    /// The hex sha256 of its bytes.
    pub sha256: String,
    /// The size of its bytes.
    pub size: i64,
    /// Its script, for a module written as one (TypeScript or JavaScript, run by the host's
    /// runtime of scripts); `None` for a compiled module.
    pub source: Option<String>,
    /// What it may do.
    pub grants: ModuleGrants,
    /// When this version was uploaded.
    pub uploaded_at: DateTime<Utc>,
}

/// What a module may do, granted by the operator who uploads it. Nothing by default.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct ModuleGrants {
    /// The hosts it may send HTTP requests to: `api.example.com`, `127.0.0.1:8080` (that port
    /// only), or `*.example.com` (its subdomains).
    pub allowed_hosts: Vec<String>,
    /// How long a node of it may run; `None` for the runtime's default.
    pub timeout: Option<Duration>,
    /// How much memory it may use, in MiB; `None` for the runtime's default.
    pub memory_limit_mb: Option<u32>,
    /// The names of the host's secrets it may read ([`crate::secrets`]); their values are
    /// redacted from what its nodes return, throw and log.
    pub secrets: Vec<String>,
}

/// A module's bytes as uploaded, with what it may do.
#[derive(Debug, Clone, Default)]
pub struct ModuleUpload {
    pub bytes: Vec<u8>,
    pub grants: ModuleGrants,
}

/// Why a module can't be uploaded or run.
#[derive(Debug, thiserror::Error)]
pub enum ModuleError {
    /// The upload isn't a module the runtime can run.
    #[error("{0}")]
    Invalid(String),
    /// A stored module couldn't be loaded or run.
    #[error("{0}")]
    Runtime(String),
    #[error(transparent)]
    Database(#[from] sqlx::Error),
}
