/// The job a module's job form inserted, from where the form went: its id, worker, queue, args,
/// max attempts, state, and whether it's scheduled past 50 seconds from now.
async fn inserted(
    db: &TestDb,
    res: axum::response::Response,
) -> (i64, String, String, Value, i32, String, bool) {
    assert_eq!(res.status(), StatusCode::SEE_OTHER);
    let location = res.headers()[header::LOCATION].to_str().unwrap();
    let id: i64 = location
        .strip_prefix("/admin/jobs/")
        .and_then(|id| id.parse().ok())
        .unwrap_or_else(|| panic!("to the job's page, not {location}"));
    let (worker, queue, args, max_attempts, state, later) = sqlx::query_as(&format!(
        "SELECT worker, queue, args, max_attempts, state::text,
                scheduled_at > now() + interval '50 seconds'
         FROM {}.ishikari_jobs WHERE id = $1",
        db.schema
    ))
    .bind(id)
    .fetch_one(&db.pool)
    .await
    .unwrap();
    (id, worker, queue, args, max_attempts, state, later)
}

