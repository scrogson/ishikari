//! With the host's node modules (`AppState::with_node_modules`), operators upload node types on
//! the Node types page, and the builder offers them with the types registered in Rust.

mod common;

use std::sync::{Arc, Mutex};
use std::time::Duration;

use axum::body::Body;
use axum::http::{header, Request, StatusCode};
use axum::Router;
use chrono::Utc;
use common::{body, get};
use ishikari::execution::{
    ModuleError, ModuleGrants, ModuleUpload, NodeHandler, NodeModule, NodeModules, NodeSpec,
    SchemaField,
};
use ishikari_admin::AppState;
use serde_json::{json, Value};
use tower::ServiceExt;

/// Modules kept in memory, whose bytes are their spec as JSON.
#[derive(Default)]
struct Shelf {
    kept: Mutex<Vec<NodeModule>>,
    uploads: Mutex<Vec<ModuleUpload>>,
}

impl Shelf {
    fn with(modules: &[NodeSpec]) -> Arc<Shelf> {
        let shelf = Shelf::default();
        for spec in modules {
            shelf.keep(spec.clone(), b"{}".len(), ModuleGrants::default());
        }
        Arc::new(shelf)
    }

    fn keep(&self, spec: NodeSpec, size: usize, grants: ModuleGrants) -> NodeModule {
        let mut kept = self.kept.lock().unwrap();
        let latest = kept.iter().rfind(|m| m.spec.name == spec.name);
        if let Some(latest) = latest.filter(|m| m.size == size as i64 && m.grants == grants) {
            return latest.clone();
        }
        let module = NodeModule {
            version: latest.map_or(1, |m| m.version + 1),
            spec,
            sha256: format!("{size:064x}"),
            size: size as i64,
            grants,
            uploaded_at: Utc::now(),
        };
        kept.push(module.clone());
        module
    }
}

#[async_trait::async_trait]
impl NodeModules for Shelf {
    async fn handler(
        &self,
        _: &str,
        _: chrono::DateTime<Utc>,
    ) -> Result<Option<Arc<dyn NodeHandler>>, ModuleError> {
        Ok(None)
    }

    async fn modules(&self) -> Result<Vec<NodeModule>, ModuleError> {
        let kept = self.kept.lock().unwrap();
        let mut latest: Vec<NodeModule> = Vec::new();
        for module in kept.iter() {
            latest.retain(|m| m.spec.name != module.spec.name);
            latest.push(module.clone());
        }
        latest.sort_by(|a, b| a.spec.name.cmp(&b.spec.name));
        Ok(latest)
    }

    async fn describe(&self, bytes: &[u8]) -> Result<NodeSpec, ModuleError> {
        serde_json::from_slice(bytes)
            .map_err(|e| ModuleError::Invalid(format!("not a node module: {e}")))
    }

    async fn upload(&self, upload: ModuleUpload) -> Result<NodeModule, ModuleError> {
        self.uploads.lock().unwrap().push(upload.clone());
        let spec = self.describe(&upload.bytes).await?;
        Ok(self.keep(spec, upload.bytes.len(), upload.grants))
    }
}

fn slack_post() -> NodeSpec {
    NodeSpec::new("slack/post")
        .category("chat")
        .input("text", SchemaField::string().required())
}

fn kit() -> NodeSpec {
    NodeSpec::new("test/kit")
        .category("test")
        .description("Shouts")
        .input("text", SchemaField::string())
}

/// The admin at `/admin`, with `slack/post` registered in Rust and `modules`, if any. Nothing
/// here reaches the database.
fn admin(modules: Option<Arc<Shelf>>) -> Router {
    let pool = sqlx::PgPool::connect_lazy("postgres://localhost/unused").unwrap();
    let mut state = AppState::new(pool)
        .with_base_path("/admin")
        .with_node_types(vec![slack_post()]);
    if let Some(modules) = modules {
        state = state.with_node_modules(modules);
    }
    Router::new().nest("/admin", ishikari_admin::app(state))
}

/// POST `fields` (a part with a file name is the module) as `multipart/form-data`.
async fn upload(app: &Router, fields: &[(&str, &[u8])]) -> axum::response::Response {
    let boundary = "ik-test-boundary";
    let mut form = Vec::new();
    for (name, value) in fields {
        form.extend_from_slice(format!("--{boundary}\r\n").as_bytes());
        if *name == "module" {
            form.extend_from_slice(
                b"Content-Disposition: form-data; name=\"module\"; filename=\"kit.wasm\"\r\n\
                  Content-Type: application/wasm\r\n\r\n",
            );
        } else {
            form.extend_from_slice(
                format!("Content-Disposition: form-data; name=\"{name}\"\r\n\r\n").as_bytes(),
            );
        }
        form.extend_from_slice(value);
        form.extend_from_slice(b"\r\n");
    }
    form.extend_from_slice(format!("--{boundary}--\r\n").as_bytes());
    app.clone()
        .oneshot(
            Request::post("/admin/node-types")
                .header(
                    header::CONTENT_TYPE,
                    format!("multipart/form-data; boundary={boundary}"),
                )
                .body(Body::from(form))
                .unwrap(),
        )
        .await
        .unwrap()
}

async fn palette(app: &Router) -> Vec<String> {
    let res = get(app, "/admin/api/node-types", &[]).await;
    assert_eq!(res.status(), StatusCode::OK);
    let types: Value = serde_json::from_str(&body(res).await).unwrap();
    types["node_types"]
        .as_array()
        .unwrap()
        .iter()
        .map(|t| t["name"].as_str().unwrap().to_string())
        .collect()
}

async fn validate(app: &Router, node_type: &str) -> Value {
    let def = json!({ "name": "notify", "nodes": { "a": { "type": node_type } } });
    let res = app
        .clone()
        .oneshot(
            Request::post("/admin/api/definitions/validate")
                .header(header::CONTENT_TYPE, "application/json")
                .body(Body::from(def.to_string()))
                .unwrap(),
        )
        .await
        .unwrap();
    serde_json::from_str(&body(res).await).unwrap()
}

/// The palette offers the types registered in Rust, then the uploaded modules; a module named
/// as a registered type isn't offered, as it wouldn't run. A definition may use either.
#[tokio::test]
async fn the_builder_offers_uploaded_modules_too() {
    let shadowed = NodeSpec::new("slack/post").category("modules");
    let app = admin(Some(Shelf::with(&[kit(), shadowed])));

    assert_eq!(palette(&app).await, ["slack/post", "test/kit"]);
    let res = get(&app, "/admin/api/node-types", &[]).await;
    let types: Value = serde_json::from_str(&body(res).await).unwrap();
    assert_eq!(types["node_types"][0]["category"], "chat");
    assert_eq!(types["node_types"][1]["description"], "Shouts");

    assert_eq!(validate(&app, "test/kit").await["valid"], json!(true));
    assert_eq!(validate(&app, "slack/post").await["valid"], json!(true));
    let refused = validate(&app, "pager/send").await;
    assert_eq!(refused["valid"], json!(false));
    assert_eq!(
        refused["errors"][0]["message"],
        "Unknown node type 'pager/send'"
    );
}

/// The Node types page lists the registered types and the uploaded modules, with what each
/// module may do, and the form to upload one; the navigation links to it.
#[tokio::test]
async fn the_node_types_page_lists_both() {
    let shelf = Shelf::with(&[]);
    shelf.keep(
        kit(),
        2048,
        ModuleGrants {
            allowed_hosts: vec!["api.example.com".into(), "*.internal".into()],
            timeout: Some(Duration::from_millis(2500)),
            memory_limit_mb: Some(32),
        },
    );
    let app = admin(Some(shelf));

    let res = get(&app, "/admin/node-types", &[]).await;
    assert_eq!(res.status(), StatusCode::OK);
    let page = body(res).await;
    assert!(page.contains(r#"href="/admin/node-types""#), "nav link");
    for text in [
        "slack/post",
        "test/kit",
        "Shouts",
        "v1",
        "api.example.com",
        "*.internal",
        "2.5s",
        "32 MiB",
        "2.0 KiB",
        r#"enctype="multipart/form-data""#,
        r#"action="/admin/node-types""#,
    ] {
        assert!(page.contains(text), "the page shows {text:?}");
    }
}

/// Without modules, the page lists the registered types only, offers no upload, and isn't in
/// the navigation; nothing can be uploaded.
#[tokio::test]
async fn without_modules_nothing_is_uploaded() {
    let app = admin(None);

    let res = get(&app, "/admin/node-types", &[]).await;
    assert_eq!(res.status(), StatusCode::OK);
    let page = body(res).await;
    assert!(page.contains("slack/post"));
    assert!(!page.contains("multipart/form-data"));
    let res = get(&app, "/admin/", &[]).await;
    assert!(!body(res).await.contains(r#"href="/admin/node-types""#));

    let res = upload(&app, &[("module", kit_bytes().as_slice())]).await;
    assert_eq!(res.status(), StatusCode::NOT_FOUND);
}

fn kit_bytes() -> Vec<u8> {
    serde_json::to_vec(&kit()).unwrap()
}

/// An upload is kept with the grants the form gives, and the page says so. The same upload
/// again changes nothing, and the page says that.
#[tokio::test]
async fn an_upload_is_kept_with_its_grants() {
    let shelf = Shelf::with(&[]);
    let app = admin(Some(shelf.clone()));
    let bytes = kit_bytes();
    let fields: &[(&str, &[u8])] = &[
        ("module", &bytes),
        (
            "allowed_hosts",
            b"api.example.com\r\n *.internal , 127.0.0.1:8080\r\n",
        ),
        ("timeout_seconds", b"2.5"),
        ("memory_limit_mb", b"32"),
    ];

    let res = upload(&app, fields).await;
    assert_eq!(res.status(), StatusCode::SEE_OTHER);
    let location = res.headers()[header::LOCATION]
        .to_str()
        .unwrap()
        .to_string();
    assert_eq!(
        location,
        "/admin/node-types?uploaded=test%2Fkit&version=1&unchanged=false"
    );
    let uploads = shelf.uploads.lock().unwrap().clone();
    assert_eq!(uploads.len(), 1);
    assert_eq!(uploads[0].bytes, bytes);
    assert_eq!(
        uploads[0].grants,
        ModuleGrants {
            allowed_hosts: vec![
                "api.example.com".into(),
                "*.internal".into(),
                "127.0.0.1:8080".into()
            ],
            timeout: Some(Duration::from_millis(2500)),
            memory_limit_mb: Some(32),
        }
    );
    let page = body(get(&app, &location, &[]).await).await;
    assert!(page.contains("Uploaded test/kit v1"), "{page}");

    let res = upload(&app, fields).await;
    let location = res.headers()[header::LOCATION]
        .to_str()
        .unwrap()
        .to_string();
    assert!(location.ends_with("version=1&unchanged=true"), "{location}");
    let page = body(get(&app, &location, &[]).await).await;
    assert!(
        page.contains("test/kit v1 already has these bytes and grants"),
        "{page}"
    );

    // Blank limits are the runtime's defaults.
    let res = upload(
        &app,
        &[
            ("module", &bytes),
            ("allowed_hosts", b""),
            ("timeout_seconds", b""),
            ("memory_limit_mb", b""),
        ],
    )
    .await;
    assert_eq!(res.status(), StatusCode::SEE_OTHER);
    let last = shelf.uploads.lock().unwrap().last().unwrap().grants.clone();
    assert_eq!(last, ModuleGrants::default());
}

/// A form's fields, by name.
type Fields<'a> = Vec<(&'a str, &'a [u8])>;

/// An upload that can't be kept is refused with why, the form keeping what was entered: no
/// module, a limit that isn't one, bytes that aren't a module, or a module named as a type
/// registered in Rust, which would never run.
#[tokio::test]
async fn an_upload_refused_says_why() {
    let shelf = Shelf::with(&[]);
    let app = admin(Some(shelf.clone()));
    let bytes = kit_bytes();
    let rust_named = serde_json::to_vec(&NodeSpec::new("slack/post")).unwrap();

    let cases: Vec<(Fields, &str)> = vec![
        (
            vec![("allowed_hosts", b"api.example.com")],
            "Choose a module to upload",
        ),
        (
            vec![("module", &bytes), ("timeout_seconds", b"soon")],
            "The timeout must be a number of seconds",
        ),
        (
            vec![("module", &bytes), ("memory_limit_mb", b"-1")],
            "The memory limit must be a whole number of MiB",
        ),
        (vec![("module", b"\0asm")], "not a node module"),
        (
            vec![("module", &rust_named)],
            "slack/post is registered in Rust",
        ),
    ];
    for (fields, why) in cases {
        let res = upload(&app, &fields).await;
        assert_eq!(res.status(), StatusCode::BAD_REQUEST, "{why}");
        let page = body(res).await;
        assert!(page.contains(why), "{why}: {page}");
        assert!(page.contains(r#"enctype="multipart/form-data""#));
    }

    let res = upload(
        &app,
        &[("module", b"nope"), ("allowed_hosts", b"kept.example.com")],
    )
    .await;
    assert!(body(res).await.contains("kept.example.com"));
    // Each was refused before it was uploaded.
    assert!(shelf.uploads.lock().unwrap().is_empty());
}
